#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
make-book-deps.py — per-boek bronbestandenlijst uit latexmk' .fls.

Probleem: de Nederlandse boeken deelden één voorwaardenlijst (alle dutch/*.tex),
waardoor één hoofdstukbewerking alle zes boeken achterhaald maakte. Elk boek
laadt echter een eigen deelverzameling (regtables, keymap-tabellen,
instructieset- en opcode-tabellen worden indirect geladen en staan dus niet in
de boeksmaster). De .fls die latexmk bij elke run schrijft is daarom de
waarheid: `INPUT`-regels uit de laatste run zijn exact de gebruikte bronnen.

Gebruik (vanuit dutch/):
    python3 tools/make-book-deps.py            # alle boeken uit de .fls
    python3 tools/make-book-deps.py <boek>...  # alleen deze boeken

Schrijft build/<boek>.deps met één regel per boek:
    mega65-userguide.pdf: appendix-foo.tex ... ../fonts.tex ...

Het doel-bestand krijgt GEEN recept, zodat de patroonregel in de Makefile
blijft gelden; -include in de Makefile voegt de bestanden toe als normale
voorwaarden. De mtime van het .deps-bestand speelt dus geen rol — alleen de
inhoud telt.

Bewust uitgesloten:
  - dutch/build/**          : de gegenereerde wrapper (zelfreferentie)
  - uitvoerextensies        : .aux/.log/.toc/... (worden tijdens de run herschreven)
  - gitinfo.tex             : ./getgitinfo herschrijft dit elke build; zou elke
                              book-pdf permanent achterhaald maken
  - *.aux van het grote boek: die cross-verwijzing loopt via de stamp in de
                              Makefile (build/mega65-book.stamp), niet via de
                              gewone voorwaarden
"""
import os
import sys

OUT_EXT = (
    '.aux', '.log', '.out', '.toc', '.lof', '.lot', '.idx', '.ind', '.ilg',
    '.bbl', '.blg', '.bc', '.bcf', '.run.xml', '.fls', '.fdb_latexmk', '.pdf',
    '.dvi', '.xdv', '.synctex', '.synctex.gz', '.nav', '.snm', '.vrb', '.auxlock',
    '.idxrun', '.glo', '.gls', '.ist', '.spl', '.listing',
)

HERE = os.path.dirname(os.path.abspath(__file__))
LANGDIR = os.path.dirname(HERE)   # the language subdir (dutch/, ...)
ROOT = os.path.dirname(LANGDIR)
BUILD_DIR = os.path.join(LANGDIR, 'build')

BOOKS = ['mega65-book', 'mega65-userguide', 'mega65-developer-guide',
         'mega65-assembly-reference', 'mega65-chipset-reference',
         'mega65-basic65-reference']

# Het boek waarvan de deelboeken hun kruisverwijzingen ophalen (de aux).
CROSSREF_BOOK = 'mega65-book'


def other_book_file(name, book):
    """True als `name` een artefact van een ander boek is.

    De eigen master (dutch/mega65-<boek>.tex) blijft wél een voorwaarde: hij
    wordt met de hand onderhouden. De aux van elk boek vervalt: het grote
    boek loopt via de stamp in de Makefile, en de eigen aux is uitvoer.
    """
    base = os.path.basename(name)
    for b in BOOKS:
        if base == b + '.aux':
            return True
        if b != book and base == b + '.tex':
            return True
    return False


def is_output(name):
    if name.startswith('build/'):
        return True
    if os.path.basename(name) == 'gitinfo.tex':
        return True
    return name.endswith(OUT_EXT)


def collect(book):
    """Lees de .fls van `book`; retourneer (gesorteerde bronnen, of None)."""
    fls = os.path.join(LANGDIR, book + '.fls')
    if not os.path.exists(fls):
        return None
    deps = set()
    with open(fls, encoding='utf-8', errors='replace') as f:
        for line in f:
            if not line.startswith('INPUT '):
                continue
            p = line[6:].strip()
            if p.startswith('./'):
                p = p[2:]
            # shell-escape-probes (bijv. "extractbb --version") hebben spaties
            if not p or any(c.isspace() for c in p):
                continue
            ap = os.path.normpath(os.path.join(ROOT, p))
            # alleen repo-bestanden volgen; systeem-fonts e.d. negeren
            if not ap.startswith(ROOT + os.sep):
                continue
            if not os.path.isfile(ap):
                continue
            rel = os.path.relpath(ap, LANGDIR)
            if other_book_file(rel, book):
                continue
            if is_output(rel):
                continue
            deps.add(rel.replace(os.sep, '/'))
    return sorted(deps)


def render(book, deps):
    head = ['# Generated by dutch/tools/make-book-deps.py from %s.fls.' % book,
            '# Do not edit by hand; `make deps` refreshes this.']
    targets = ['%s.pdf' % book]
    if book == CROSSREF_BOOK:
        # The big book also feeds the cross-reference check that the sub-books
        # rely on (see the Makefile). Same source list, different target.
        targets.append('build/%s.checked' % book)
    if not deps:
        head.append('%s: # no sources recorded yet' % targets[0])
        return '\n'.join(head) + '\n'
    out = head[:]
    for target in targets:
        line = target + ':'
        first = True
        for d in deps:
            piece = ' ' + d
            if not first and len(line) + len(piece) + 2 > 76:
                # NB: de backslash moet aan het regeleinde staan, niet gevolgd door
                # een spatie - anders escapt hij de spatie en plakt die aan het pad.
                out.append(line + ' \\')
                line = '  ' + d
            else:
                line += piece
            first = False
        out.append(line)
    return '\n'.join(out) + '\n'


def write(path, text):
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, path)


def main(argv):
    books = argv[1:] or BOOKS
    # accept both 'mega65-book' and the pattern-rule stem 'book'
    books = [b if b.startswith('mega65-') else 'mega65-' + b for b in books]
    if not os.path.isdir(BUILD_DIR):
        os.makedirs(BUILD_DIR)
    rc = 0
    for b in books:
        deps = collect(b)
        if deps is None:
            print('%-28s geen .fls gevonden (boek nog nooit gebouwd) — '
                  'overslaan' % b)
            rc = 1
            continue
        p = os.path.join(BUILD_DIR, b + '.deps')
        write(p, render(b, deps))
        print('%-28s %d bronbestanden -> build/%s.deps' % (b, len(deps), b))
    return rc


if __name__ == '__main__':
    sys.exit(main(sys.argv))
